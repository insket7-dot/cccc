// scripts/generate-entity-barrel.js
const fs = require('fs');
const path = require('path');

const entitiesDir = path.join(__dirname, '..', 'src', 'app', 'shared', 'entities');
const barrelFile = path.join(entitiesDir, 'index.ts');

try {
    const files = fs.readdirSync(entitiesDir);

    const entityFiles = files.filter(file =>
        file.endsWith('.entity.ts') && file !== 'index.ts'
    );

    const header = `// This file is auto-generated by scripts/generate-entity-barrel.js. Do not edit manually.\n\n`;
    const exports = entityFiles
        .map(file => `export * from './${file.replace('.ts', '')}';`)
        .join('\n');

    const content = header + exports + '\n';

    fs.writeFileSync(barrelFile, content, 'utf8');

    console.log(`✅ Successfully generated entity barrel at: ${barrelFile}`);

} catch (error) {
    console.error(`❌ Error generating entity barrel:`, error);
    process.exit(1);
}

